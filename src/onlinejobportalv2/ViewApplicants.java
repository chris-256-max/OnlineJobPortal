private void loadApplicants() {
    String sql = "SELECT a.application_id, j.job_title, " +
                 "u.full_name, u.email, a.application_date, " +
                 "s.status_name FROM applications a " +
                 "JOIN jobs j ON a.job_id = j.job_id " +
                 "JOIN companies c ON j.company_id = c.company_id " +
                 "JOIN job_seekers js ON a.seeker_id = js.seeker_id " +
                 "JOIN users u ON js.user_id = u.user_id " +
                 "JOIN application_status s ON a.status_id = s.status_id " +
                 "WHERE c.employer_id = ?";

    try {
        java.sql.Connection conn = DatabaseConnection.getConnection();
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
        pst.setInt(1, employerId);

        java.sql.ResultSet rs = pst.executeQuery();
        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
            tblApplicants.getModel();

        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("application_id"),
                rs.getString("job_title"),
                rs.getString("full_name"),
                rs.getString("email"),
                rs.getDate("application_date"),
                rs.getString("status_name")
            });
        }

        conn.close();
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
    }
}



private void updateApplicationStatus(int statusId) {
    int row = tblApplicants.getSelectedRow();

    if (row == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Please select an applicant first!"
        );
        return;
    }

    int applicationId = Integer.parseInt(
        tblApplicants.getValueAt(row, 0).toString()
    );

    String sql = "UPDATE applications a " +
                 "JOIN jobs j ON a.job_id = j.job_id " +
                 "JOIN companies c ON j.company_id = c.company_id " +
                 "SET a.status_id = ? " +
                 "WHERE a.application_id = ? AND c.employer_id = ?";

    try {
        java.sql.Connection conn = DatabaseConnection.getConnection();
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);

        pst.setInt(1, statusId);
        pst.setInt(2, applicationId);
        pst.setInt(3, employerId);
        pst.executeUpdate();

        conn.close();
        loadApplicants();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Application status updated!"
        );
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

