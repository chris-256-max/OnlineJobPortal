    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        
int row = tblSkills.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Please select a skill first!"
    );
    return;
}

int skillId = Integer.parseInt(
    tblSkills.getValueAt(row, 0).toString()
);

try {
    java.sql.Connection conn = DatabaseConnection.getConnection();

    java.sql.PreparedStatement pst = conn.prepareStatement(
        "DELETE FROM job_seeker_skills WHERE seeker_id = ? AND skill_id = ?"
    );
    pst.setInt(1, seekerId);
    pst.setInt(2, skillId);
    pst.executeUpdate();

    conn.close();
    loadSkills();

    javax.swing.JOptionPane.showMessageDialog(
        this, "Skill removed successfully!"
    );

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnRemoveActionPerformed

