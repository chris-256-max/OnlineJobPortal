    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        
String skillName = txtSkill.getText().trim();

if (skillName.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Please enter a skill name!"
    );
    return;
}

try {
    java.sql.Connection conn = DatabaseConnection.getConnection();

    java.sql.PreparedStatement check = conn.prepareStatement(
        "SELECT skill_id FROM skills WHERE skill_name = ?"
    );
    check.setString(1, skillName);

    java.sql.ResultSet rs = check.executeQuery();
    int skillId;

    if (rs.next()) {
        skillId = rs.getInt("skill_id");
    } else {
        java.sql.PreparedStatement insertSkill = conn.prepareStatement(
            "INSERT INTO skills (skill_name) VALUES (?)",
            java.sql.Statement.RETURN_GENERATED_KEYS
        );
        insertSkill.setString(1, skillName);
        insertSkill.executeUpdate();

        java.sql.ResultSet keys = insertSkill.getGeneratedKeys();
        keys.next();
        skillId = keys.getInt(1);
    }

    java.sql.PreparedStatement link = conn.prepareStatement(
        "SELECT * FROM job_seeker_skills WHERE seeker_id = ? AND skill_id = ?"
    );
    link.setInt(1, seekerId);
    link.setInt(2, skillId);

    java.sql.ResultSet linked = link.executeQuery();

    if (!linked.next()) {
        java.sql.PreparedStatement addLink = conn.prepareStatement(
            "INSERT INTO job_seeker_skills (seeker_id, skill_id) VALUES (?, ?)"
        );
        addLink.setInt(1, seekerId);
        addLink.setInt(2, skillId);
        addLink.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Skill added successfully!"
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "You already have this skill!"
        );
    }

    conn.close();
    txtSkill.setText("");
    loadSkills();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnAddActionPerformed

