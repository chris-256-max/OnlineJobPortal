    private void btnApplyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApplyActionPerformed
        
int row = tblJobs.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Please select a job first!"
    );
    return;
}

String jobTitle = tblJobs.getValueAt(row, 0).toString();

String sql = "SELECT job_id FROM jobs WHERE job_title = ? LIMIT 1";

try {
    java.sql.Connection conn = DatabaseConnection.getConnection();

    java.sql.PreparedStatement pst = conn.prepareStatement(sql);
    pst.setString(1, jobTitle);

    java.sql.ResultSet rs = pst.executeQuery();

    if (rs.next()) {
        int jobId = rs.getInt("job_id");

        String insert = "INSERT INTO applications " +
                "(seeker_id, job_id, application_date, status_id) " +
                "VALUES (?, ?, CURDATE(), 1)";

        java.sql.PreparedStatement pst2 =
                conn.prepareStatement(insert);

        pst2.setInt(1, seekerId);
        pst2.setInt(2, jobId);

        pst2.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Application submitted successfully!"
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Job not found!"
        );
    }

    conn.close();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error: " + e.getMessage()
    );
}
        
    }//GEN-LAST:event_btnApplyActionPerformed

