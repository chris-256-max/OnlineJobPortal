    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String search = txtSearch.getText().trim();

String sql = "SELECT j.job_title, c.company_name, " +
             "jc.category_name, jt.type_name, " +
             "l.location_name, j.salary " +
             "FROM jobs j " +
             "JOIN companies c ON j.company_id = c.company_id " +
             "JOIN job_categories jc ON j.category_id = jc.category_id " +
             "JOIN job_types jt ON j.type_id = jt.type_id " +
             "JOIN locations l ON j.location_id = l.location_id " +
             "WHERE j.job_title LIKE ?";

try {
    java.sql.Connection conn = DatabaseConnection.getConnection();
    java.sql.PreparedStatement pst = conn.prepareStatement(sql);

    pst.setString(1, "%" + search + "%");

    java.sql.ResultSet rs = pst.executeQuery();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblJobs.getModel();

    model.setRowCount(0);

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getString("job_title"),
            rs.getString("company_name"),
            rs.getString("category_name"),
            rs.getString("type_name"),
            rs.getString("location_name"),
            rs.getDouble("salary")
        });
    }

    conn.close();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

