private void loadResume() {
    String sql = "SELECT resume_title, summary, resume_file " +
                 "FROM resumes WHERE seeker_id = ?";

    try {
        java.sql.Connection conn = DatabaseConnection.getConnection();
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);

        pst.setInt(1, seekerId);

        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()){
txtResumeTitle.setText(rs.getString("resume_title"));
txtSummary.setText(rs.getString("summary"));
txtFile.setText(rs.getString("resume_file"));
        }

        conn.close();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

