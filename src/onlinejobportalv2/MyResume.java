    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String title = txtResumeTitle.getText().trim();
        String summary = txtSummary.getText().trim();
        String file = txtFile.getText().trim();
        
        if (title.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a resume title!");
            return;
        }
        
        try{
            java.sql.Connection conn = DatabaseConnection.getConnection();
            java.sql.PreparedStatement check = conn.prepareStatement("SELECT resume_id FROM resumes WHERE seeker_id = ?");
            check.setInt(1, seekerId);
            java.sql.ResultSet rs = check.executeQuery();
            
            if (rs.next()){
                java.sql.PreparedStatement update = conn.prepareStatement("UPDATE resumes SET resume_title = ?, summary = ?, " + "resume_file = ? WHERE seeker_id = ?");
                
                update.setString(1, title);
                update.setString(2, summary);
                update.setString(3, file);
                update.setInt(4, seekerId);
                update.executeUpdate();
            } else {
               java.sql.PreparedStatement insert = conn.prepareStatement("INSERT INTO resumes (seeke_id, resume_title, summary, " + "resume_file) VALUES (?, ?, ?, ?)");
               insert.setInt(1, seekerId);
               insert.setString(2, title);
               insert.setString(3, summary);
               insert.setString(4, file);
               insert.executeUpdate();
            }
            
            conn.close();
            
            javax.swing.JOptionPane.showMessageDialog(this, "Resume saved Successfully!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error:" + e.getMessage());
        }
    }//GEN-LAST:event_btnSaveActionPerformed

